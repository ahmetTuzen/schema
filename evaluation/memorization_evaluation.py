import os
import logging

import numpy as np
import pandas as pd

from alignment import generates_features, infer_model, node_align, strip_sample_suffix
from utils import report_fidelity, load_baselines

from memorization_metrics import edge_overlap, self_overlap, neighborhood_memorization, nndr


logger = logging.getLogger(__name__)


def _flatten(d, prefix=""):
    """Flatten the nested memorization_report dict into one row of scalar columns."""
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(_flatten(v, prefix + k + "_"))
        else:
            out[prefix + k] = v
    return out


def _group_samples(baselines):
    """Group independent samples per model: 'schema_0','schema_1' -> 'schema'."""
    groups = {}
    for name, g in baselines.items():
        groups.setdefault(strip_sample_suffix(name), []).append(g)
    return groups


def _resolve_alignment(name, samples):
    """
    Node alignment class as mentioned in the paper.
    """
    align = getattr(samples[0], "node_alignment", None)
    if align:
        return align
    model = infer_model(name)
    if model is None:
        return "unknown"
    return node_align(model)


def _id_space_ok(samples, num_nodes):
    """
    Simply checking if the generated graph exceeding number of nodes.
    It is also okay if the graph generating less than original.
    But not okay if node id exceeding the max nodes.
    """
    hi = 0
    for g in samples:
        ei = g.edge_index
        hi = max(hi, int(ei.max()) + 1 if ei.numel() else 0)
        hi = max(hi, int(getattr(g, "num_nodes", 0) or 0))
    return hi <= num_nodes, hi



def memorization_fidelity(args, cfg):
    if args.evaluation_mode == "report":
        save_path = os.path.join(args.csv_location, "memorization", cfg.dataset.name + ".csv")
        mem_df = pd.read_csv(save_path)

    elif args.evaluation_mode in ("calculate", "append"):
        logger.info("Calculating memorization fidelity...")
        results = calculate_memorization_fidelity(args, cfg)
        logger.info("Memorization evaluation completed. Saving .csv, then reporting...")
        mem_df, save_path = save_memorization_fidelity(args, cfg, results)

    report_fidelity(mem_df, save_path)



def calculate_memorization_fidelity(args, cfg):

    baselines = load_baselines(cfg)
    if "Original" not in baselines:
        logger.warning("Original graph not found... skipping. Empty .csv will be created.")
        return {}

    real = baselines["Original"]
    ref_ei = real.edge_index.cpu().numpy()
    num_nodes = real.num_nodes

    real_x = real.x.cpu().numpy() if getattr(real, "x", None) is not None else None

    groups = _group_samples(baselines)

    results = {}
    for name, samples in groups.items():
        if name == "Original":
            continue

        alignment = _resolve_alignment(name, samples)
        
        if alignment == "none":
            logger.warning(f"There is no alignment between reference and {name}, skipping memorization evaluation.")
            continue

        gen_eis = [g.edge_index.cpu().numpy() for g in samples]

        ids_ok, hi = _id_space_ok(samples, num_nodes)

        if not ids_ok:
            logger.warning(f"[{name}] node IDs exceed the reference space ({hi} > {num_nodes}): No memorization will be reported for {name}.")
            continue

        if len(samples) < 2:
            logger.warning(f"[{name}] only 1 sample, not reporting memorization metrics")
            continue

        row = {}

        gen_eis_list = list(gen_eis)

        edge_ov_mean = float(np.mean([edge_overlap(ref_ei, g) for g in gen_eis_list]))

        self_ov, self_ov_std = self_overlap(gen_eis_list, return_std=True)

        nm = [neighborhood_memorization(ref_ei, g, num_nodes) for g in gen_eis_list]
        nm_mean = {k: float(np.mean([d[k] for d in nm])) for k in nm[0]}

        row["edge_overlap"] = edge_ov_mean
        row["self_overlap"] = self_ov
        row["self_overlap_std"] = self_ov_std
        row["neighborhood_memorization"] = nm_mean["neighbour_jaccard_mean"]
        row["memorized_node_frac"] = nm_mean["memorized_node_frac"]
        
        # row = _flatten(rep)
        row["node_alignment"] = alignment
        row["n_gen_nodes"] = int(np.median([g.num_nodes for g in samples]))


        model = infer_model(name)
        if real_x is not None:
            if not generates_features(model):
                logger.info(f"[{name}] features are not generated by the model; skipping feature memorization.")
            else:
                xs = [g.x.cpu().numpy() for g in samples if getattr(g, "x", None) is not None and g.x.shape[1] == real_x.shape[1]]
                if not xs:
                    logger.warning(f"[{name}] no usable features (missing or dimension != {real_x.shape[1]}); skipping feature memorization.")
                else:
                    pv = [nndr(real_x, gx) for gx in xs[:10]]
                    row.update({f"privacy_{k}": float(np.mean([d[k] for d in pv])) for k in pv[0]})
                    row["privacy_n_samples"] = len(pv)

        results[name] = row

    return results


def save_memorization_fidelity(args, cfg, results):
    save_path = os.path.join(args.csv_location, "memorization", cfg.dataset.name + ".csv")
    os.makedirs(os.path.dirname(save_path), exist_ok=True)

    df = pd.DataFrame.from_dict(results, orient="index")
    df.index.name = "model"
    df = df.reset_index()

    if args.evaluation_mode == "append" and os.path.exists(save_path):
        df_old = pd.read_csv(save_path)
        df = pd.concat([df_old, df], ignore_index=True)
        df = df.drop_duplicates(subset=["model"], keep="last")

    df.to_csv(save_path, index=False)
    return df, save_path
